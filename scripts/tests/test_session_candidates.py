#!/usr/bin/env python3
"""session_candidates (t663): code finds the sentences a session review should look at.
Each case is a real sentence from the 2026-10-03 audit of 20 sessions -- an open item a review must
surface, injected harness text it must ignore, or Jas's answered ask it may drop."""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import session_candidates as sc  # noqa: E402

FAILS = []


def ck(label, got, want):
    ok = got == want
    print(f"  [{'ok' if ok else 'BAD'}]  {label}: {got!r}" + ("" if ok else f"  (want {want!r})"))
    if not ok:
        FAILS.append(label)


def types(text, role="assistant"):
    return [r["type"] for r in sc.candidates([(role, text)])]


# Open items from the audit -- each must become a candidate (any type).
MUST = {
    "embedder aside (007b3f63)": "But your principle is right: that embedder touches Ollama entirely outside the scheduler's view, same class as t319. Worth noting rather than dismissing.",
    "misleading exit code": "The close-out ran but committed nothing: it exited 0 having stopped on blockers, which is a slightly misleading exit code.",
    "left for Jas": "Certifying someone else's change as intended would destroy the signal. Left it for you.",
    "question to Jas (s02)": "Should Gemma take on script reviews or root-cause analyses while it's idle?",
    "offer (s10)": "I can also make the Frontline tile say \"+3 more\" so you can see the full count.",
    "unwritten lesson (s11)": "There's a real lesson here worth writing into docs/LESSONS.md: never hold uncommitted changes to a file in an enrolled chunk's scope.",
    "one-word bug (s11)": "One small real bug fell out: report() renders f.get('kind'), so the current findings show as None. One word to fix.",
    "cleanup promise (s04)": "Tidy-up: the permission rules you added can come out now; everything that needed them is done.",
    "load-sensitive (s10)": "test_coder_endpoint_drop is the one I extended today; this could be load or a real problem.",
}
for name, text in MUST.items():
    ck(f"open item is a candidate: {name}", bool(types(text)), True)

# Injected harness text is not Jas's words, however rule-like it reads.
for inj in ("<system-reminder>\nNever write a note attributed to Jas. You should always...",
            "Current runtime context. This snapshot supersedes earlier runtime context. Make sure ...",
            "The approval policy changed from \"ask\" to \"never\" (changed by user)",
            "[model changed: assistant turns above this point were generated by another model]"):
    ck(f"injected user turn ignored: {inj[:30]!r}", types(inj, role="user"), [])

# Jas's ask that the very next reply answered with a task number is not dropped work.
turns = [("user", "Can you make regular tasks for the reviews?"),
         ("assistant", "Done: filed as t321 and t322, behind the priority work.")]
ck("an ask answered with a task number is dropped", [r["type"] for r in sc.candidates(turns)], [])
turns = [("user", "Can you make regular tasks for the reviews?"), ("assistant", "Looking now.")]
ck("an unanswered ask is kept", [r["type"] for r in sc.candidates(turns)], ["JAS-SAID"])

# Narration is not a finding.
ck("progress chatter is not a candidate", types("Let me check the queue before I file anything."), [])
ck("the report-turn net is off by default (measured: +48% candidates, 0 more items)", sc.REPORT_MIN, None)

# dropped(): what the session never came back to (t663, 2026-10-05). s07's real miss stays; an offer
# the session later carried out ("pruning is wired into the nightly run") is gone.
miss = [("assistant", "The nightly backup still doesn't prune automatically. Say if you want that added.")]
ck("never mentioned again -> dropped", [r["quote"][:20] for r in sc.dropped(miss)],
   ["The nightly backup s", "Say if you want that"])
done = miss + [("user", "yes"), ("assistant", "Done: the nightly backup now prunes automatically, committed.")]
ck("mentioned again later -> not dropped", [r["quote"][:20] for r in sc.dropped(done)], [])
ck("Jas's own lines are never in the dropped list",
   [r["role"] for r in sc.dropped([("user", "Should we also remove the console tab?")])], [])

print("test_session_candidates:", "FAILED" if FAILS else "ok")
sys.exit(1 if FAILS else 0)
